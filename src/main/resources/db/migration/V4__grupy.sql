CREATE TABLE grupa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazwa VARCHAR(160) NOT NULL,
    rodzaj VARCHAR(40) NOT NULL,
    opis VARCHAR(2000),
    termin VARCHAR(160),
    miejsce VARCHAR(160),
    lider_id BIGINT,
    aktywna BOOLEAN NOT NULL,
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT fk_grupa_lider FOREIGN KEY (lider_id) REFERENCES osoba (id)
);

CREATE TABLE czlonek_grupy (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupa_id BIGINT NOT NULL,
    osoba_id BIGINT NOT NULL,
    funkcja VARCHAR(80),
    od_dnia DATE,
    do_dnia DATE,
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT uq_czlonek_grupy UNIQUE (grupa_id, osoba_id),
    CONSTRAINT fk_czlonek_grupa FOREIGN KEY (grupa_id) REFERENCES grupa (id),
    CONSTRAINT fk_czlonek_osoba FOREIGN KEY (osoba_id) REFERENCES osoba (id)
);
