CREATE TABLE obecnosc (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rodzaj VARCHAR(20) NOT NULL,
    cel_id BIGINT NOT NULL,
    osoba_id BIGINT NOT NULL,
    obecny BOOLEAN NOT NULL,
    uwagi VARCHAR(300),
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT uq_obecnosc UNIQUE (rodzaj, cel_id, osoba_id),
    CONSTRAINT fk_obecnosc_osoba FOREIGN KEY (osoba_id) REFERENCES osoba (id)
);

CREATE INDEX idx_obecnosc_cel ON obecnosc (rodzaj, cel_id);
