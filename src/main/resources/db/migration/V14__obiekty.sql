CREATE TABLE obiekt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazwa VARCHAR(160) NOT NULL,
    rodzaj VARCHAR(40) NOT NULL,
    rodzic_id BIGINT,
    pojemnosc INT,
    lokalizacja VARCHAR(200),
    opis VARCHAR(1000),
    aktywny BOOLEAN NOT NULL,
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT fk_obiekt_rodzic FOREIGN KEY (rodzic_id) REFERENCES obiekt (id)
);

CREATE TABLE rezerwacja_obiektu (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obiekt_id BIGINT NOT NULL,
    poczatek TIMESTAMP NOT NULL,
    koniec TIMESTAMP NOT NULL,
    rezerwujacy VARCHAR(160) NOT NULL,
    osoba_id BIGINT,
    cel VARCHAR(200),
    liczba_osob INT,
    status VARCHAR(30) NOT NULL,
    uwagi VARCHAR(1000),
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT fk_rezerwacja_obiekt FOREIGN KEY (obiekt_id) REFERENCES obiekt (id),
    CONSTRAINT fk_rezerwacja_osoba FOREIGN KEY (osoba_id) REFERENCES osoba (id)
);

CREATE INDEX idx_rezerwacja_obiekt_poczatek ON rezerwacja_obiektu (obiekt_id, poczatek);

