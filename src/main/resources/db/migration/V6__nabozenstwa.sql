CREATE TABLE nabozenstwo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wydarzenie_id BIGINT NOT NULL,
    rodzaj VARCHAR(40) NOT NULL,
    niedziela_roku VARCHAR(160),
    kaznodzieja VARCHAR(160),
    czytanie_starego VARCHAR(200),
    psalm VARCHAR(200),
    czytanie_apostolskie VARCHAR(200),
    ewangelia VARCHAR(200),
    tytul_kazania VARCHAR(200),
    werset_kazania VARCHAR(200),
    wieczerza_panska BOOLEAN NOT NULL,
    uwagi_liturgiczne VARCHAR(2000),
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT uq_nabozenstwo_wydarzenie UNIQUE (wydarzenie_id),
    CONSTRAINT fk_nabozenstwo_wydarzenie FOREIGN KEY (wydarzenie_id) REFERENCES wydarzenie (id) ON DELETE CASCADE
);

CREATE TABLE piesn_nabozenstwa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nabozenstwo_id BIGINT NOT NULL,
    kolejnosc INT NOT NULL,
    numer_spiewnika VARCHAR(20),
    tytul VARCHAR(200) NOT NULL,
    moment VARCHAR(40) NOT NULL,
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT fk_piesn_nabozenstwo FOREIGN KEY (nabozenstwo_id) REFERENCES nabozenstwo (id) ON DELETE CASCADE
);
