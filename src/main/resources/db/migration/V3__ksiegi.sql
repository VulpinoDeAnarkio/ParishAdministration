CREATE TABLE chrzest (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    osoba_id BIGINT NOT NULL,
    data_chrztu DATE NOT NULL,
    miejsce VARCHAR(200) NOT NULL,
    duchowny VARCHAR(160) NOT NULL,
    rodzic_1 VARCHAR(160),
    rodzic_2 VARCHAR(160),
    chrzestny_1 VARCHAR(160),
    chrzestny_2 VARCHAR(160),
    numer_ksiegi VARCHAR(40) NOT NULL,
    uwagi VARCHAR(1000),
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT uq_chrzest_osoba UNIQUE (osoba_id),
    CONSTRAINT uq_chrzest_numer UNIQUE (numer_ksiegi),
    CONSTRAINT fk_chrzest_osoba FOREIGN KEY (osoba_id) REFERENCES osoba (id)
);

