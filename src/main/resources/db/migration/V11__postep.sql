CREATE TABLE cel_parafii (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazwa VARCHAR(200) NOT NULL,
    opis VARCHAR(1000),
    zrodlo VARCHAR(40) NOT NULL,
    wartosc_docelowa DECIMAL(12, 2) NOT NULL,
    wartosc_reczna DECIMAL(12, 2),
    rok INT NOT NULL,
    aktywny BOOLEAN NOT NULL,
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT ck_cel_docelowa CHECK (wartosc_docelowa > 0)
);

CREATE TABLE rocznik_konfirmacyjny (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazwa VARCHAR(160) NOT NULL,
    rok INT NOT NULL,
    data_konfirmacji DATE,
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL
);

CREATE TABLE uczestnik_rocznika (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rocznik_id BIGINT NOT NULL,
    osoba_id BIGINT NOT NULL,
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT uq_uczestnik_rocznika UNIQUE (rocznik_id, osoba_id),
    CONSTRAINT fk_uczestnik_rocznik FOREIGN KEY (rocznik_id) REFERENCES rocznik_konfirmacyjny (id),
    CONSTRAINT fk_uczestnik_osoba FOREIGN KEY (osoba_id) REFERENCES osoba (id)
);

CREATE TABLE lekcja (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rocznik_id BIGINT NOT NULL,
    data_lekcji DATE NOT NULL,
    temat VARCHAR(200) NOT NULL,
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT fk_lekcja_rocznik FOREIGN KEY (rocznik_id) REFERENCES rocznik_konfirmacyjny (id)
);

CREATE TABLE obecnosc_lekcji (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lekcja_id BIGINT NOT NULL,
    osoba_id BIGINT NOT NULL,
    obecny BOOLEAN NOT NULL,
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT uq_obecnosc_lekcji UNIQUE (lekcja_id, osoba_id),
    CONSTRAINT fk_obecnosc_lekcji_lekcja FOREIGN KEY (lekcja_id) REFERENCES lekcja (id) ON DELETE CASCADE,
    CONSTRAINT fk_obecnosc_lekcji_osoba FOREIGN KEY (osoba_id) REFERENCES osoba (id)
);
