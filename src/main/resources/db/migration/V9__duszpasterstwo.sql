CREATE TABLE sprawa_duszpasterska (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    osoba_id BIGINT NOT NULL,
    temat VARCHAR(200) NOT NULL,
    opis VARCHAR(4000),
    status VARCHAR(20) NOT NULL,
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT fk_sprawa_osoba FOREIGN KEY (osoba_id) REFERENCES osoba (id)
);

CREATE TABLE wizyta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sprawa_id BIGINT,
    osoba_id BIGINT NOT NULL,
    data_wizyty DATE NOT NULL,
    miejsce VARCHAR(160),
    notatka VARCHAR(4000),
    nastepny_kontakt DATE,
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT fk_wizyta_sprawa FOREIGN KEY (sprawa_id) REFERENCES sprawa_duszpasterska (id),
    CONSTRAINT fk_wizyta_osoba FOREIGN KEY (osoba_id) REFERENCES osoba (id)
);
