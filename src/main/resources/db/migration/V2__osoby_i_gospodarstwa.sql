CREATE TABLE gospodarstwo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazwa VARCHAR(160) NOT NULL,
    ulica VARCHAR(160),
    kod_pocztowy VARCHAR(12),
    miejscowosc VARCHAR(120),
    telefon VARCHAR(40),
    uwagi VARCHAR(1000),
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL
);

CREATE TABLE osoba (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imie VARCHAR(80) NOT NULL,
    drugie_imie VARCHAR(80),
    nazwisko VARCHAR(80) NOT NULL,
    nazwisko_rodowe VARCHAR(80),
    plec VARCHAR(20) NOT NULL,
    data_urodzenia DATE,
    miejsce_urodzenia VARCHAR(160),
    email VARCHAR(180),
    telefon VARCHAR(40),
    ulica VARCHAR(160),
    kod_pocztowy VARCHAR(12),
    miejscowosc VARCHAR(120),
    status VARCHAR(40) NOT NULL,
    rola_w_rodzinie VARCHAR(30),
    data_przyjecia DATE,
    data_wystapienia DATE,
    zgoda_na_kontakt BOOLEAN NOT NULL,
    uczestniczy_w_wieczerzy BOOLEAN NOT NULL,
    uwagi VARCHAR(2000),
    gospodarstwo_id BIGINT,
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT fk_osoba_gospodarstwo FOREIGN KEY (gospodarstwo_id) REFERENCES gospodarstwo (id)
);

CREATE INDEX idx_osoba_nazwisko ON osoba (nazwisko, imie);
CREATE INDEX idx_osoba_status ON osoba (status);
CREATE INDEX idx_osoba_gospodarstwo ON osoba (gospodarstwo_id);
