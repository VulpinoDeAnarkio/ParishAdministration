CREATE TABLE operacja (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fundusz_id BIGINT NOT NULL,
    rodzaj VARCHAR(40) NOT NULL,
    kierunek VARCHAR(20) NOT NULL,
    kwota DECIMAL(12, 2) NOT NULL,
    data_operacji DATE NOT NULL,
    opis VARCHAR(500),
    kontrahent VARCHAR(160),
    osoba_id BIGINT,
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT ck_operacja_kwota CHECK (kwota > 0),
    CONSTRAINT fk_operacja_fundusz FOREIGN KEY (fundusz_id) REFERENCES fundusz (id),
    CONSTRAINT fk_operacja_osoba FOREIGN KEY (osoba_id) REFERENCES osoba (id)
);

CREATE INDEX idx_operacja_fundusz ON operacja (fundusz_id, data_operacji);
