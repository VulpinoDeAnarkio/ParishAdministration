CREATE TABLE sala (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazwa VARCHAR(160) NOT NULL,
    pojemnosc INT,
    opis VARCHAR(500),
    aktywna BOOLEAN NOT NULL,
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL
);

