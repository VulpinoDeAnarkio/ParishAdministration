CREATE TABLE wydarzenie (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tytul VARCHAR(200) NOT NULL,
    opis VARCHAR(2000),
    poczatek TIMESTAMP NOT NULL,
    koniec TIMESTAMP NOT NULL,
    miejsce VARCHAR(200),
    sala_id BIGINT,
    rodzaj VARCHAR(40) NOT NULL,
    widoczne_publicznie BOOLEAN NOT NULL,
    organizator VARCHAR(160),
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT fk_wydarzenie_sala FOREIGN KEY (sala_id) REFERENCES sala (id)
);

CREATE INDEX idx_wydarzenie_poczatek ON wydarzenie (poczatek);
