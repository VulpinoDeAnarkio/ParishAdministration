CREATE TABLE ogloszenie (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tytul VARCHAR(200) NOT NULL,
    tresc VARCHAR(4000) NOT NULL,
    obowiazuje_od DATE NOT NULL,
    obowiazuje_do DATE,
    widoczne_publicznie BOOLEAN NOT NULL,
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL
);
