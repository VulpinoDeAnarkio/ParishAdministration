CREATE TABLE dyzur (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nabozenstwo_id BIGINT NOT NULL,
    osoba_id BIGINT NOT NULL,
    rola VARCHAR(40) NOT NULL,
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT uq_dyzur UNIQUE (nabozenstwo_id, osoba_id, rola),
    CONSTRAINT fk_dyzur_nabozenstwo FOREIGN KEY (nabozenstwo_id) REFERENCES nabozenstwo (id) ON DELETE CASCADE,
    CONSTRAINT fk_dyzur_osoba FOREIGN KEY (osoba_id) REFERENCES osoba (id)
);

CREATE TABLE zadanie (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tytul VARCHAR(200) NOT NULL,
    opis VARCHAR(2000),
    termin DATE,
    status VARCHAR(20) NOT NULL,
    osoba_id BIGINT,
    wydarzenie_id BIGINT,
    utworzono TIMESTAMP NOT NULL,
    zmodyfikowano TIMESTAMP NOT NULL,
    CONSTRAINT fk_zadanie_osoba FOREIGN KEY (osoba_id) REFERENCES osoba (id),
    CONSTRAINT fk_zadanie_wydarzenie FOREIGN KEY (wydarzenie_id) REFERENCES wydarzenie (id)
);
